def make_bird(name, p):
    bl, bw, bh, bz = p["bl"], p["bw"], p["bh"], p["bz"]
    tilt = -12  # tail up
    blob("body", p["body"], "body", (0, 0.02 * bl, bz), (bw, bl, bh), rot=(tilt, 0, 0), seg=8, rings=6, taper=0.35, seed=len(name))
    # breast lighter / belly: small blob in front
    nb = Vector((0, -bl * 0.38, bz + bh * 0.25))
    ang = math.radians(p["na"])
    nt = nb + Vector((0, -math.sin(ang), math.cos(ang))) * p["nl"]
    cone("neck", p["head"] if p["nl"] > 0.1 else p["body"], "neck", nb - Vector((0, -0.01, 0.03)), nt, bw * 0.28, bw * 0.2, sides=6)
    hc = nt + Vector((0, -p["hr"] * 0.35, p["hr"] * 0.35))
    blob("head", p["head"], "head", hc, (p["hr"] * 1.8, p["hr"] * 2.2, p["hr"] * 1.9), seg=7, rings=5)
    # eyes
    for s in (-1, 1):
        blob("eye", "black", "head", hc + Vector((s * p["hr"] * 0.82, -p["hr"] * 0.35, p["hr"] * 0.25)), (p["hr"] * 0.28,) * 3, seg=4, rings=3)
    bb = hc + Vector((0, -p["hr"] * 0.95, -p["hr"] * 0.1))
    if p["beak"] == "flat":
        cone("beak", p["beakc"], "head", bb, bb + Vector((0, -p["bk"], -p["bk"] * 0.2)), p["hr"] * 0.45, p["hr"] * 0.3, sides=4, flat=1.6)
    elif p["beak"] == "goose":
        cone("beak", p["beakc"], "head", bb, bb + Vector((0, -p["bk"], -p["bk"] * 0.15)), p["hr"] * 0.45, p["hr"] * 0.2, sides=5, flat=1.2)
    elif p["beak"] == "crow":
        cone("beak", p["beakc"], "head", bb, bb + Vector((0, -p["bk"], -p["bk"] * 0.25)), p["hr"] * 0.42, 0, sides=4, flat=0.9)
    else:
        cone("beak", p["beakc"], "head", bb, bb + Vector((0, -p["bk"], -p["bk"] * 0.3)), p["hr"] * 0.32, 0, sides=4)
    if p["comb"]:
        big = 1.6 if name == "rooster" else 1.0
        top = hc + Vector((0, 0, p["hr"] * 0.85))
        plate("comb", p["comb"], "head", [top + Vector((0, p["hr"] * 0.6, -0.005)), top + Vector((0, p["hr"] * 0.35, p["hr"] * 0.55 * big)),
              top + Vector((0, 0, p["hr"] * 0.45 * big)), top + Vector((0, -p["hr"] * 0.3, p["hr"] * 0.6 * big)), top + Vector((0, -p["hr"] * 0.6, -0.005))], 0.012)
        wt = bb + Vector((0, 0.005, -p["hr"] * 0.35))
        plate("wattle", p["comb"], "head", [wt, wt + Vector((0, -p["hr"] * 0.2, -p["hr"] * 0.55 * big)), wt + Vector((0, p["hr"] * 0.3, -p["hr"] * 0.4 * big))], 0.012)
    # wings: folded plates on the flanks
    for s, side in ((-1, "R"), (1, "L")):
        w0 = Vector((s * bw * 0.46, -bl * 0.25, bz + bh * 0.22))
        blob("wing" + side, p["wing"], "wing." + side, w0 + Vector((s * 0.004, bl * 0.28, -bh * 0.05)),
             (bw * 0.16, bl * 0.72, bh * 0.55), rot=(tilt - 6, s * 8, 0), seg=6, rings=4, taper=0.55, seed=3)
    # tail
    tb = Vector((0, bl * 0.42, bz + bh * 0.12))
    if p["tailk"] == "rooster":
        for i, (dx, up) in enumerate(((-0.02, 0.9), (0.0, 1.1), (0.02, 0.8))):
            plate("tail%d" % i, p["tail"], "tail", [tb + Vector((dx, -0.02, -0.01)), tb + Vector((dx, 0.10, 0.10 * up + 0.08)),
                  tb + Vector((dx, 0.16, 0.06 * up + 0.02)), tb + Vector((dx, 0.07, -0.03))], 0.01)
    elif p["tailk"] == "hen":
        cone("tail", p["tail"], "tail", tb, tb + Vector((0, bl * 0.25, bh * 0.45)), bw * 0.28, bw * 0.08, sides=5, flat=0.5)
    elif p["tailk"] == "fan":
        plate("tail", p["tail"], "tail", [tb + Vector((-bw * 0.12, 0, 0)), tb + Vector((-bw * 0.22, bl * 0.45, -bh * 0.08)),
              tb + Vector((bw * 0.22, bl * 0.45, -bh * 0.08)), tb + Vector((bw * 0.12, 0, 0))], 0.008)
    else:
        cone("tail", p["tail"], "tail", tb, tb + Vector((0, bl * 0.2, bh * 0.18)), bw * 0.25, bw * 0.05, sides=5, flat=0.45)
    # legs + feet
    lz = p["legz"]
    for s, side in ((-1, "R"), (1, "L")):
        hip = Vector((s * bw * 0.2, bl * 0.02, lz + 0.01))
        foot = Vector((s * bw * 0.22, bl * 0.0, 0.004))
        cone("leg" + side, p["leg"], "leg." + side, foot, hip + Vector((0, 0, bh * 0.25)), max(0.006, bw * 0.045), max(0.005, bw * 0.04), sides=4)
        fl = max(0.03, bl * 0.18) if p["beak"] in ("flat", "goose") else max(0.025, bl * 0.14)
        if p["beak"] in ("flat", "goose"):
            plate("foot" + side, p["leg"], "leg." + side, [foot + Vector((-fl * 0.5, -fl, 0)), foot + Vector((fl * 0.5, -fl, 0)), foot + Vector((0, fl * 0.2, 0))], 0.006)
        else:
            for a in (-25, 0, 25):
                d = Vector((math.sin(math.radians(a)), -math.cos(math.radians(a)), 0)) * fl
                cone("toe", p["leg"], "leg." + side, foot, foot + d, 0.005, 0.002, sides=3)
    # rig
    neck_mid = nb
    arm = build_rig([
        ("root", (0, 0, 0), (0, 0, bz * 0.5), None),
        ("body", (0, bl * 0.1, bz), (0, -bl * 0.3, bz + bh * 0.1), "root"),
        ("neck", tuple(nb), tuple(nt), "body"),
        ("head", tuple(nt), tuple(hc + Vector((0, -p["hr"], 0))), "neck"),
        ("tail", tuple(tb), tuple(tb + Vector((0, bl * 0.25, bh * 0.2))), "body"),
        ("wing.L", (bw * 0.4, -bl * 0.2, bz + bh * 0.3), (bw * 0.45, bl * 0.35, bz + bh * 0.2), "body"),
        ("wing.R", (-bw * 0.4, -bl * 0.2, bz + bh * 0.3), (-bw * 0.45, bl * 0.35, bz + bh * 0.2), "body"),
        ("leg.L", (bw * 0.2, bl * 0.02, lz + bh * 0.2), (bw * 0.22, 0, 0.004), "body"),
        ("leg.R", (-bw * 0.2, bl * 0.02, lz + bh * 0.2), (-bw * 0.22, 0, 0.004), "body"),
    ])
    obj = assemble(arm)
    return arm, obj, dict(bz=bz, bh=bh, bl=bl, lz=lz)


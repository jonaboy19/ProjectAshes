def make_rabbit(body="rabbit", light="rabbit_lt"):
    bl, bw, bh, bz = 0.26, 0.15, 0.15, 0.095
    blob("body", body, "body", (0, 0.03, bz), (bw, bl, bh), rot=(-8, 0, 0), seg=8, rings=6, taper=-0.25, seed=5)
    blob("belly", light, "body", (0, -0.03, bz - 0.035), (bw * 0.7, bl * 0.6, bh * 0.45), seg=6, rings=4)
    hc = Vector((0, -bl * 0.45, bz + bh * 0.45))
    blob("head", body, "head", hc, (0.075, 0.095, 0.075), rot=(15, 0, 0), seg=7, rings=5, seed=2)
    blob("muzzle", light, "head", hc + Vector((0, -0.04, -0.015)), (0.04, 0.03, 0.03), seg=5, rings=3)
    blob("nose", "pink_ear", "head", hc + Vector((0, -0.055, -0.004)), (0.012, 0.01, 0.01), seg=4, rings=3)
    for s in (-1, 1):
        blob("eye", "black", "head", hc + Vector((s * 0.033, -0.022, 0.012)), (0.014, 0.014, 0.016), seg=4, rings=3)
        side = "L" if s > 0 else "R"
        eb = hc + Vector((s * 0.018, 0.012, 0.03))
        blob("ear" + side, body, "ear." + side, eb + Vector((s * 0.008, 0.012, 0.055)), (0.028, 0.012, 0.11), rot=(-15, s * 12, 0), seg=5, rings=4)
        blob("earin" + side, "pink_ear", "ear." + side, eb + Vector((s * 0.008, 0.006, 0.058)), (0.016, 0.006, 0.08), rot=(-15, s * 12, 0), seg=4, rings=3)
        # front legs
        blob("fleg" + side, body, "fleg." + side, (s * 0.038, -bl * 0.33, 0.04), (0.03, 0.034, 0.085), seg=5, rings=4)
        # hind legs: haunch + long foot
        blob("haunch" + side, body, "hleg." + side, (s * 0.058, bl * 0.24, 0.07), (0.055, 0.12, 0.105), rot=(-15, 0, 0), seg=6, rings=4)
        blob("hfoot" + side, body, "hleg." + side, (s * 0.058, bl * 0.14, 0.014), (0.032, 0.11, 0.028), seg=5, rings=3)
    blob("tail", "white", "tail", (0, bl * 0.55, bz + 0.03), (0.045, 0.04, 0.045), seg=5, rings=4)
    arm = build_rig([
        ("root", (0, 0, 0), (0, 0, 0.06), None),
        ("body", (0, bl * 0.3, bz), (0, -bl * 0.3, bz + 0.02), "root"),
        ("head", tuple(hc + Vector((0, 0.03, -0.03))), tuple(hc + Vector((0, -0.07, 0))), "body"),
        ("ear.L", (0.02, hc.y + 0.012, hc.z + 0.03), (0.03, hc.y + 0.03, hc.z + 0.15), "head"),
        ("ear.R", (-0.02, hc.y + 0.012, hc.z + 0.03), (-0.03, hc.y + 0.03, hc.z + 0.15), "head"),
        ("fleg.L", (0.04, -bl * 0.3, bz - 0.02), (0.04, -bl * 0.32, 0.0), "body"),
        ("fleg.R", (-0.04, -bl * 0.3, bz - 0.02), (-0.04, -bl * 0.32, 0.0), "body"),
        ("hleg.L", (0.058, bl * 0.28, 0.08), (0.058, bl * 0.1, 0.01), "body"),
        ("hleg.R", (-0.058, bl * 0.28, 0.08), (-0.058, bl * 0.1, 0.01), "body"),
        ("tail", (0, bl * 0.5, bz + 0.02), (0, bl * 0.62, bz + 0.05), "body"),
    ])
    obj = assemble(arm)
    return arm, obj, dict(bz=bz)


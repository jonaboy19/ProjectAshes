PARTS = []  # (obj, bone)

def _obj(bm, name, colour, bone):
    me = bpy.data.meshes.new(name); bm.to_mesh(me); bm.free()
    o = bpy.data.objects.new(name, me); bpy.context.scene.collection.objects.link(o)
    mat = bpy.data.materials.get(colour) or bpy.data.materials.new(colour)
    me.materials.append(mat)
    vg = o.vertex_groups.new(name=bone); vg.add([v.index for v in me.vertices], 1.0, "REPLACE")
    PARTS.append((o, bone)); return o

def blob(name, colour, bone, centre, size, rot=(0, 0, 0), seg=8, rings=6, taper=0.0, jitter=0.0, seed=1):
    """faceted ellipsoid; taper narrows the -Y (front) or +Y end: taper>0 narrows back end"""
    bm = bmesh.new()
    bmesh.ops.create_uvsphere(bm, u_segments=seg, v_segments=rings, radius=0.5)
    import random; r = random.Random(seed)
    for v in bm.verts:
        v.co.x *= size[0]; v.co.y *= size[1]; v.co.z *= size[2]
        if taper:
            k = 1 - taper * (v.co.y / max(size[1], 1e-6) + 0.5)
            v.co.x *= max(k, 0.2); v.co.z *= max(0.35 + 0.65 * k, 0.2)
        if jitter:
            v.co += Vector((r.uniform(-1, 1), r.uniform(-1, 1), r.uniform(-1, 1))) * jitter
    m = mathutils.Euler([math.radians(a) for a in rot]).to_matrix().to_4x4()
    bmesh.ops.transform(bm, matrix=Matrix.Translation(Vector(centre)) @ m, verts=bm.verts)
    return _obj(bm, name, colour, bone)

def cone(name, colour, bone, base, tip, r1, r2=0.0, sides=5, flat=1.0):
    bm = bmesh.new()
    d = Vector(tip) - Vector(base); ln = d.length
    bmesh.ops.create_cone(bm, cap_ends=True, cap_tris=False, segments=sides, radius1=r1, radius2=max(r2, 0.0005), depth=ln)
    for v in bm.verts: v.co.x *= flat; v.co.z += ln / 2
    q = Vector((0, 0, 1)).rotation_difference(d.normalized())
    bmesh.ops.transform(bm, matrix=Matrix.Translation(Vector(base)) @ q.to_matrix().to_4x4(), verts=bm.verts)
    return _obj(bm, name, colour, bone)

def plate(name, colour, bone, pts, thick=0.004):
    """flat polygon (list of 3D points) extruded slightly"""
    bm = bmesh.new()
    vs = [bm.verts.new(p) for p in pts]
    f = bm.faces.new(vs)
    ext = bmesh.ops.extrude_face_region(bm, geom=[f])
    nv = [e for e in ext["geom"] if isinstance(e, bmesh.types.BMVert)]
    f.normal_update()
    bmesh.ops.translate(bm, vec=f.normal * -thick, verts=nv)
    bmesh.ops.recalc_face_normals(bm, faces=bm.faces)
    return _obj(bm, name, colour, bone)

# ------------------------------------------------------------------ rig
def build_rig(bones):
    """bones: list of (name, head, tail, parent)"""
    ad = bpy.data.armatures.new("AnimalRig"); arm = bpy.data.objects.new("AnimalArmature", ad)
    bpy.context.scene.collection.objects.link(arm)
    bpy.context.view_layer.objects.active = arm
    bpy.ops.object.mode_set(mode="EDIT")
    eb = {}
    for n, h, t, p in bones:
        b = ad.edit_bones.new(n); b.head = h; b.tail = t
        if p: b.parent = eb[p]
        eb[n] = b
    bpy.ops.object.mode_set(mode="OBJECT")
    return arm

def assemble(arm):
    bpy.ops.object.select_all(action="DESELECT")
    for o, b in PARTS: o.select_set(True)
    bpy.context.view_layer.objects.active = PARTS[0][0]
    bpy.ops.object.join()
    obj = bpy.context.view_layer.objects.active; obj.name = "Body"
    # merge coincident verts inside the same part is not needed; keep faceted
    obj.parent = arm
    m = obj.modifiers.new("Armature", "ARMATURE"); m.object = arm
    PARTS.clear()
    return obj


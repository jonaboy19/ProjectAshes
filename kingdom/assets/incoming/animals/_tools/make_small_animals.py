    # Fly (flap) for flying birds; flightless chickens get a short flutter
    if fly:
        tuck = {"leg.L": [(X, -70)], "leg.R": [(X, -70)], "body": [(X, 0)]}
        up = dict(tuck); up.update({"wing.L": [(Y, -80)], "wing.R": [(Y, 80)], "tail": [(X, -5)]})

"""Capture views for the W4 sites and stamps -> kingdom/tools_qa/region1/w4_views.json (read by tools_qa/region1/look_capture.gd).
   py -I kingdom/tools/region1/gen_w4_views.py <sites dump .jsonl from tools_qa/region1/w4_dump.gd>
View = {"name", "at": [x, z], "look": [x, z], "up", "look_up", "hour", "fov", "warm"} (metres, north = -z)."""
import json, math, os, sys

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "tools_qa", "region1", "w4_views.json")
sites = [json.loads(l) for l in open(sys.argv[1], encoding="utf-8")]
by_name = {s["name"]: s for s in sites}
by_r1 = {s["r1id"]: s for s in sites if s["r1id"]}
views = []


def rot(x, z, a):
    return x * math.cos(a) - z * math.sin(a), x * math.sin(a) + z * math.cos(a)


def v(name, at, look, up=3.0, look_up=2.0, hour=15.0, fov=60, warm=170):
    views.append({"name": name, "at": [round(at[0], 1), round(at[1], 1)], "look": [round(look[0], 1), round(look[1], 1)], "up": up, "look_up": look_up,
                  "hour": hour, "fov": fov, "warm": warm})


def front(s, d, ang=0.5):
    f = (math.sin(s["yaw"]), math.cos(s["yaw"]))
    dx, dz = rot(f[0] * d, f[1] * d, ang)
    return (s["x"] + dx, s["z"] + dz)


# --- W4 sites -------------------------------------------------------------------------------
for rid, s in by_r1.items():
    if not rid.startswith("w4_") or "milestone" in rid:
        continue
    grove = "grove" in rid
    d = 15 if grove else (22 if "edge" in rid or "market" in rid else 18)
    if rid == "w4_greenhollow_fields":
        d = 26
    v("site_" + rid[3:], front(s, d), (s["x"], s["z"]), up=7.0 if grove else 3.2, look_up=5.0 if grove else 2.0, fov=62)
for rid in ["w4_milestones_ember_1", "w4_milestones_greenhollow_3"]:
    s = by_r1[rid]
    v("site_" + rid[3:], front(s, 14, 0.3), (s["x"], s["z"]), up=2.4, look_up=1.2)

# --- Scar Mouth Arena (moved to its canon point) ----------------------------------------------
a = by_r1["scar_arena"]
v("site_scar_arena", front(a, 34, 0.5), (a["x"], a["z"]), up=5.0, look_up=2.5)

# --- stamps ----------------------------------------------------------------------------------
rift = by_name["The Rift"]
rx, rz = rift["x"], rift["z"]
ang = math.radians(25.0)
U = (math.cos(ang), math.sin(ang))
Vn = (-math.sin(ang), math.cos(ang))
def P(c, u, w):
    return (c[0] + u * U[0] + w * Vn[0], c[1] + u * U[1] + w * Vn[1])
v("stamp_rift_aerial", P((rx, rz), -140, 190), (rx, rz), up=150, look_up=0, fov=65, warm=200)
v("stamp_rift_along", P((rx, rz), -130, 34), P((rx, rz), 80, 0), up=3.0, look_up=-4.0, fov=70, warm=200)
v("stamp_rift_lip", P((rx, rz), 20, 46), (rx, rz), up=2.2, look_up=-6.0, fov=75, warm=200)
mouth = by_r1["w4_rift_mouth"]
mx, mz = mouth["x"], mouth["z"]
v("stamp_scar_aerial", (mx - 200, mz + 230), (mx, mz), up=130, look_up=0, fov=65, warm=220)
v("stamp_scar_rim", (mx - 135, mz + 20), (mx, mz), up=2.4, look_up=-3.0, fov=70, warm=200)
v("stamp_scar_satellite", (mx + 190, mz - 120), (mx + 40, mz + 10), up=40, look_up=0, fov=60, warm=200)
for n, key in [("greyseam", "Greyseam Mine"), ("deepvein", "Deepvein Mine"), ("coldseam", "Coldseam Mine"), ("ironroot", "Ironroot Mine")]:
    s = by_name[key]
    v("stamp_mine_" + n, front(s, 20, 0.35), (s["x"] - math.sin(s["yaw"]) * 3, s["z"] - math.cos(s["yaw"]) * 3), up=3.4, look_up=3.0, fov=62, warm=200)
    v("stamp_mine_%s_side" % n, front(s, 36, 1.2), (s["x"], s["z"]), up=8.0, look_up=2.0, fov=60, warm=170)
g = by_name["Grimfen Pass"]
v("stamp_grimfen_front", (g["x"] + 80, g["z"] + 10), (g["x"], g["z"]), up=3.0, look_up=4.0, fov=62, warm=200)
v("stamp_grimfen_aerial", (g["x"] + 160, g["z"] + 120), (g["x"], g["z"]), up=90, look_up=0, fov=62, warm=200)
# --- Emberglass East Landing (look-pass parts) -----------------------------------------------------
v("site_emberglass_east_landing", (-352, 322), (-326, 300), up=4.0, look_up=1.5, fov=62)
v("site_emberglass_east_landing_lake", (-300, 296), (-346, 300), up=3.0, look_up=0.5, fov=62)

with open(OUT, "w", encoding="utf-8") as f:
    json.dump({"_comment": "W4 site and stamp views for look_capture.gd (generated by tools/region1/gen_w4_views.py)", "views": views}, f, indent=1)
print("wrote", len(views), "views ->", os.path.normpath(OUT))
